import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const DATASET_URL = new URL("../data/v1-canonical-dataset.json", import.meta.url);
const OUTPUT_URL = new URL("../supabase/seed.sql", import.meta.url);
const UUID_NAMESPACE = "6ba7b811-9dad-11d1-80b4-00c04fd430c8";

function uuidBytes(uuid) {
  return Buffer.from(uuid.replaceAll("-", ""), "hex");
}

function stableUuid(name) {
  const digest = createHash("sha1")
    .update(uuidBytes(UUID_NAMESPACE))
    .update(`oahu-disposal-navigator/${name}`, "utf8")
    .digest()
    .subarray(0, 16);

  digest[6] = (digest[6] & 0x0f) | 0x50;
  digest[8] = (digest[8] & 0x3f) | 0x80;

  const hex = digest.toString("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

function sqlText(value) {
  if (value === null) return "null";
  return `'${value.replaceAll("'", "''")}'`;
}

function sqlDate(value) {
  return value === null ? "null" : `date ${sqlText(value)}`;
}

function sqlTextArray(values) {
  return `array[${values.map(sqlText).join(", ")}]::text[]`;
}

function valuesStatement(table, columns, rows) {
  const formatted = rows.map((row) => `  (${row.join(", ")})`).join(",\n");
  return `insert into ${table} (${columns.join(", ")}) values\n${formatted};`;
}

const dataset = JSON.parse(await readFile(DATASET_URL, "utf8"));
const categoryUuid = new Map(
  dataset.categories.map((category) => [category.id, stableUuid(`category/${category.id}`)]),
);
const sourceUuid = new Map(
  dataset.sources.map((source) => [source.id, stableUuid(`source/${source.id}`)]),
);
const guidanceUuid = new Map(
  dataset.categories.map((category) => [category.id, stableUuid(`guidance/${category.id}`)]),
);

const categoryRows = dataset.categories.map((category) => [
  sqlText(categoryUuid.get(category.id)),
  sqlText(category.id),
  sqlText(category.display_name),
  sqlText(category.description),
  String(category.active),
  sqlText(category.review_status),
]);

const aliasRows = dataset.categories.flatMap((category) =>
  category.aliases.map((alias) => [
    sqlText(stableUuid(`alias/${category.id}/${alias.normalized_alias}`)),
    sqlText(categoryUuid.get(category.id)),
    sqlText(alias.alias),
    sqlText(alias.normalized_alias),
    sqlText(alias.locale),
    sqlText(alias.review_status),
  ]),
);

const guidanceRows = dataset.categories.map((category) => [
  sqlText(guidanceUuid.get(category.id)),
  sqlText(categoryUuid.get(category.id)),
  sqlText(category.guidance.action_summary),
  sqlTextArray(category.guidance.requirements),
  sqlText(category.guidance.where_summary),
  sqlText(category.guidance.escalation_url),
  String(category.guidance.active),
  sqlText(category.guidance.review_status),
]);

const sourceRows = dataset.sources.map((source) => [
  sqlText(sourceUuid.get(source.id)),
  sqlText(source.id),
  sqlText(source.organization),
  sqlText(source.title),
  sqlText(source.url),
  sqlText(source.authority_level),
  sqlText(source.government_domain),
  sqlDate(source.first_retrieved_on),
  sqlDate(source.research_checked_on),
  sqlDate(source.apparent_updated_on),
  sqlText(source.date_basis),
  sqlDate(source.last_human_verified_on),
  sqlDate(source.review_by),
  String(source.review_cadence_days),
  sqlText(source.review_status),
  sqlText(source.verification_notes),
]);

const evidenceRows = dataset.evidence.map((evidence) => [
  sqlText(stableUuid(`evidence/${evidence.id}`)),
  sqlText(evidence.id),
  sqlText(sourceUuid.get(evidence.source_id)),
  sqlText(categoryUuid.get(evidence.category_id)),
  sqlText(guidanceUuid.get(evidence.category_id)),
  sqlText(evidence.locator),
  sqlText(evidence.supporting_summary),
  sqlText(evidence.claim_scope),
  sqlDate(evidence.research_checked_on),
  sqlDate(evidence.human_reviewed_on),
  sqlText(evidence.reviewer_ref),
  sqlText(evidence.review_status),
]);

const verificationRows = dataset.sources.map((source) => [
  sqlText(stableUuid(`verification/${source.id}/${source.last_human_verified_on}`)),
  sqlText(sourceUuid.get(source.id)),
  sqlDate(source.last_human_verified_on),
  sqlText("confirmed"),
  sqlText(source.verification_notes),
  sqlDate(source.apparent_updated_on),
  sqlText(dataset.approval.reviewer_ref),
]);

const sections = [
  "-- Generated by scripts/generate-supabase-seed.mjs from data/v1-canonical-dataset.json.",
  "-- Do not edit this file directly. The reviewed JSON remains the factual source artifact.",
  "begin;",
  valuesStatement(
    "private.disposal_categories",
    ["id", "slug", "display_name", "description", "active", "review_status"],
    categoryRows,
  ),
  valuesStatement(
    "private.item_aliases",
    ["id", "category_id", "alias", "normalized_alias", "locale", "review_status"],
    aliasRows,
  ),
  valuesStatement(
    "private.disposal_guidance",
    [
      "id",
      "category_id",
      "action_summary",
      "requirements",
      "where_summary",
      "escalation_url",
      "active",
      "review_status",
    ],
    guidanceRows,
  ),
  valuesStatement(
    "private.official_sources",
    [
      "id",
      "stable_id",
      "organization",
      "title",
      "url",
      "authority_level",
      "government_domain",
      "first_retrieved_on",
      "research_checked_on",
      "apparent_updated_on",
      "date_basis",
      "last_verified_on",
      "review_by",
      "review_cadence_days",
      "review_status",
      "verification_notes",
    ],
    sourceRows,
  ),
  valuesStatement(
    "private.source_evidence",
    [
      "id",
      "stable_id",
      "source_id",
      "category_id",
      "guidance_id",
      "locator",
      "supporting_summary",
      "claim_scope",
      "research_checked_on",
      "reviewed_on",
      "reviewer_ref",
      "review_status",
    ],
    evidenceRows,
  ),
  valuesStatement(
    "private.source_verifications",
    ["id", "source_id", "verified_on", "result", "notes", "apparent_updated_on", "reviewer_ref"],
    verificationRows,
  ),
  "commit;",
  "",
];

const generatedSql = sections.join("\n\n");
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  const committedSql = await readFile(OUTPUT_URL, "utf8").catch(() => null);
  const normalizedCommittedSql = committedSql?.replaceAll("\r\n", "\n") ?? null;
  if (normalizedCommittedSql !== generatedSql) {
    throw new Error(
      "supabase/seed.sql is missing or stale; run npm run db:generate-seed and review the diff.",
    );
  }
} else {
  await writeFile(OUTPUT_URL, generatedSql, "utf8");
}

console.log(
  `${checkOnly ? "Verified" : "Generated"} ${fileURLToPath(OUTPUT_URL)} with ${categoryRows.length} categories, ${aliasRows.length} aliases, ${sourceRows.length} sources, and ${evidenceRows.length} evidence records.`,
);
